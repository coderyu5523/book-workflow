# 키워드 감지 없이 항상 주입 — 책 집필 프로젝트이므로

cat << 'RULES'
<WRITING_RULES_INJECTION>
## 챕터 작성 필수 규칙 (자동 주입)

### 1. 소스 코드 참조
- 해당 ex 소스 코드를 먼저 읽고, 순서와 예시를 따른다
- code-analysis, outline, scenario를 확인한다
- 임의 작성 금지. 더 나은 방법이 있으면 사용자에게 제안한다

### 2. 스토리텔링
- 오픈이의 학습 과정을 소설처럼 서술한다 (~했습니다, ~봤습니다)
- 튜토리얼 지시문 금지 (~를 입력합니다, ~해봅니다, 먼저 ~합니다)
- 대사는 포인트에만 (전체 20% 이하)
- 학습 과정이 스토리. 실패를 억지로 넣지 않는다

### 3. 이미지
- 개념 설명 있으면 무조건 그림. 하나의 개념 = 하나의 그림
- D2 또는 GEMINI PROMPT (방식 A 형식)
- 임의 판단 금지. 그림 넣을지 말지 확신 없으면 사용자에게 질문

### 4. 개념 설명
- 예시 먼저 → 정식 개념은 참고 박스(> **참고: 제목**)에 간결하게
- 구체적 버전/프레임워크 명시 X
</WRITING_RULES_INJECTION>
RULES
